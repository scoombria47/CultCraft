            @"|(?<word>" + Word + @")", Options);
        private static readonly Regex Stem = new Regex(@"^(?:" +
            String.Join("|", Stems.Keys.OrderByDescending(key => key.Length).Select(Regex.Escape)) + @")", RegexOptions.CultureInvariant);

        internal static string Translate(string text) => Translate(text, world: true);

        internal static string TranslateTerm(string term, string text) =>
            Translate(text, world: term != "Achievements/KILL_BOSS_4_NODAMAGE");

        private static string Translate(string text, bool world)
        {
            if (String.IsNullOrEmpty(text)) return text;
            if (text == "CultCraft Settings") return "Настройки CultCraft";
            return Tokens.Replace(text, match =>
            {
                if (match.Groups["word"].Success) return ConvertWord(match.Value, world);
                if (match.Groups["agreement"].Success)
                    return ConvertWord(match.Value.Substring(0, match.Length - 1) + (Char.IsUpper(match.Value[match.Length - 1]) ? 'Я' : 'я'), world);
                if (match.Groups["everything"].Success) return MemeText.MatchCase(match.Value, "всё");
                if (match.Groups["eat"].Success) return Words.Replace(match.Value, word =>
                    word.Value.Equals("есть", StringComparison.OrdinalIgnoreCase) ? MemeText.MatchCase(word.Value, "ѣсть") : ConvertWord(word.Value, world));
                if (match.Groups["peace"].Success) return Words.Replace(match.Value, word => ConvertWord(word.Value, false));
                return match.Value;
            });
        }

        private static string ConvertWord(string original, bool world)
        {
            if (Abbreviations.Contains(original)) return original;
            string word = original.ToLowerInvariant();
            if (world && World.IsMatch(word)) word = "мір" + word.Substring(3);
            if (!Exact.TryGetValue(word, out string spelling))
            {
                spelling = word;
                if (word.EndsWith("ого", StringComparison.Ordinal) || word.EndsWith("его", StringComparison.Ordinal))
                {
                    string adjective = word.Substring(0, word.Length - 3);
                    if (UnstressedGenitives.Contains(adjective))
                    {
                        bool soft = word.EndsWith("его", StringComparison.Ordinal) && "жчшщ".IndexOf(adjective[adjective.Length - 1]) < 0;
                        spelling = adjective + (soft ? "яго" : "аго");
                    }
                }
                Match root = Stem.Match(spelling);
                if (root.Success) spelling = Stems[root.Value] + spelling.Substring(root.Length);
            }

            var result = new StringBuilder(spelling);
            for (int i = 0; i + 1 < spelling.Length; i++)
                if (spelling[i] == 'и' && BeforeDecimalI.IndexOf(spelling[i + 1]) >= 0) result[i] = 'і';
            if (Consonants.IndexOf(result[result.Length - 1]) >= 0) result.Append('ъ');
            return MemeText.MatchCase(original, result.ToString());
        }
