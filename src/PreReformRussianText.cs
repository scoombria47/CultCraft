        private static readonly Regex Words = new Regex(Word, Options);
        private static readonly Regex World = new Regex(@"^мир(?:ъ|а|у|е|ѣ|ом|ы|ов|ам|ами|ах)?$", Options);
        private static readonly Regex Tokens = new Regex(MemeText.Protected +
            @"|(?<peace>\b(?:съ?[ \t]+миромъ?|миръ?[ \t]+(?:и[ \t]+соглас[иі]и|людямъ?)|миръ?(?=[ \t]+во[ \t]+вс[еёѣ]м)|(?:сохранить|заключить|установить|желаю|добиться)[ \t]+мир(?:ъ|а)?)\b)" +
