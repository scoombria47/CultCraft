        private static readonly Regex Tokens = new Regex(
            MemeText.Protected + @"|\bCult of the Lamb\b|\b(?:" + String.Join("|", Replacements.Keys
                .Where(key => key.Contains(" ") || key.Contains("-")).OrderByDescending(key => key.Length)
                .Select(key => Regex.Escape(key).Replace("'", "['’]"))) + @")\b|" + MemeText.Word,
            RegexOptions.IgnoreCase | RegexOptions.Singleline | RegexOptions.CultureInvariant);

        internal static string Translate(string text)
        {
            if (String.IsNullOrEmpty(text)) return text;
            if (Labels.TryGetValue(text, out string label)) return MemeText.MatchCase(text, label);
            return Tokens.Replace(text, ReplaceToken);
        }

        private static string ReplaceToken(Match token)
        {
            string text = token.Value;
            string lookup = text.Replace('’', '\'');
            string suffix = "";
            if (!Replacements.TryGetValue(lookup, out string word))
            {
                if (!lookup.EndsWith("'s", StringComparison.OrdinalIgnoreCase) ||
                    !Replacements.TryGetValue(lookup.Substring(0, lookup.Length - 2), out word)) return text;
                suffix = text.Substring(text.Length - 2);
                text = text.Substring(0, text.Length - 2);
            }
            if (Char.IsLower(text[0])) word = word.ToLowerInvariant();
            return MemeText.MatchCase(text, word) + suffix;
        }
