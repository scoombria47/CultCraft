        private static readonly Regex Tokens = new Regex(
            MemeText.Protected + @"|(?<![\p{L}\p{N}_])(?:" +
            String.Join("|", Lines.Keys.OrderByDescending(key => key.Length).Select(Regex.Escape)) +
            @")(?![\p{L}\p{N}_])", RegexOptions.IgnoreCase | RegexOptions.Singleline | RegexOptions.CultureInvariant);

        internal static string Translate(string text)
        {
            if (String.IsNullOrEmpty(text)) return text;
            if (Buttons.TryGetValue(text, out string button)) return MemeText.MatchCase(text, button);
            return Tokens.Replace(text, match => Lines.TryGetValue(match.Value, out string value)
                ? MemeText.MatchCase(match.Value, value) : match.Value);
        }
